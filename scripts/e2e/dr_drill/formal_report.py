def _number(value: float) -> str:
    return f"{value:g}"


CADENCES: Mapping[str, str] = {
    "rate": _number(DEFAULT_RATE_SECONDS),
    "read": _number(READ_PERIOD_SECONDS),
    "auth": _number(AUTH_PERIOD_SECONDS),
    "dns": _number(DNS_PERIOD_SECONDS),
    "amount": str(MOVEMENT_AMOUNT),
    "settle": _number(LAG_SETTLE_SECONDS),
}


def _text(lang: str, key: str, **values: object) -> str:
    return TEXTS[lang][key].format(**{**CADENCES, **values})


def _reason(lang: str, reason: str | None) -> str:
    text = reason or ""
    if lang == ES:
        for pattern, replacement in REASONS_ES:
            if pattern.fullmatch(text):
                return pattern.sub(replacement, text)
    return text


def _cell(text: object) -> str:
    return " ".join(str(text).split()).replace("|", "/")


def _table(headers: str, rows: Sequence[Sequence[object]]) -> list[str]:
    names = headers.split(" | ")
    lines = ["| " + " | ".join(names) + " |", "|" + "|".join("---" for _ in names) + "|"]
    lines += ["| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows]
    return [*lines, ""]


def _measured(lang: str, measure: Measure, unit: str = "s", digits: int = 2) -> str:
    if measure.value is None:
        return _text(lang, "not_measured", reason=_reason(lang, measure.reason))
    return f"{measure.value:.{digits}f} {unit}".strip()


def _share(lang: str, measure: Measure) -> str:
    if measure.value is None:
        return _text(lang, "not_measured", reason=_reason(lang, measure.reason))
    return f"{measure.value * 100:.1f} %"


def _stamp(moment: datetime | None) -> str:
    return "-" if moment is None else format_utc(moment)


@dataclass(frozen=True)
class RunData:
    """One run as the formal report sees it: timeline, metrics, ledger and the run result."""

    run_id: str
    timeline: Timeline
    metrics: RunMetrics
    ledger: LedgerReport | None
    verdict: str
    reason: str | None
    primary: str
    secondary: str
    started: datetime
    deposits: tuple[tuple[str, str], ...]
    refused: int

    @property
    def date(self) -> str:
        """UTC date of the start of the run."""
        return self.started.strftime("%Y-%m-%d")


def _first_region(observations: Sequence[Observation], window: PhaseWindow | None) -> str | None:
    if window is None:
        return None
    for item in observations:
        inside = item.start_utc >= window.start and (
            window.end is None or item.start_utc < window.end
        )
        if item.probe == PROBE_WRITE and item.ok and inside and item.served_by_region:
            return item.served_by_region
    return None


def _result(timeline: Timeline) -> tuple[str, str | None]:
    for event in reversed(timeline.events("phase")):
        if event.data.get("name") == RESULT_PHASE:
            reason = event.data.get("reason")
            return str(event.data.get("verdict") or UNKNOWN_VERDICT), (
                str(reason) if reason else None
            )
    return UNKNOWN_VERDICT, None


def _ledger(timeline: Timeline) -> LedgerReport | None:
    for event in reversed(timeline.events("state_snapshot")):
        if event.data.get("label") == LEDGER_LABEL:
            return LedgerReport.from_data(event.data)
    return None


def _deposits(timeline: Timeline) -> tuple[tuple[str, str], ...]:
    return tuple(
        (str(event.data.get("phase")), str(event.data.get("outcome")))
        for event in timeline.events("workflow_step")
        if event.data.get("event") == "probe_deposit"
    )


def _refused(timeline: Timeline) -> int:
    return sum(
        1
        for event in timeline.events("note")
        if str(event.data.get("text", "")).startswith("request ")
        and " refused: " in str(event.data.get("text", ""))
    )


def build_run(timeline: Timeline) -> RunData:
    """The report view of a run from its timeline; raises FormalReportError when it lacks data."""
    windows = phase_windows(timeline)
    observations = timeline.observations()
    primary = _first_region(observations, windows.get(PHASE_BASELINE))
    secondary = _first_region(observations, windows.get(PHASE_STEADY_SECONDARY))
    if primary is None or secondary is None:
        raise FormalReportError(
            f"run {timeline.run_id}: the regions cannot be told (no successful write in the "
            "baseline and steady-secondary phases); this is not a complete drill"
        )
    events = timeline.events()
    started = windows[PHASE_BASELINE].start if PHASE_BASELINE in windows else events[0].time_utc
    verdict, reason = _result(timeline)
    try:
        ledger = _ledger(timeline)
    except ValueError as error:
        raise FormalReportError(f"run {timeline.run_id}: {error}") from error
    return RunData(
        run_id=timeline.run_id,
        timeline=timeline,
        metrics=compute_metrics(timeline, primary, secondary),
        ledger=ledger,
        verdict=verdict,
        reason=reason,
        primary=primary,
        secondary=secondary,
        started=started,
        deposits=_deposits(timeline),
        refused=_refused(timeline),
    )


def load_run(folder: Path, guard: OutputGuard) -> RunData:
    """Read `timeline.json` of a run folder; the only data source of the formal report."""
    path = folder / TIMELINE_FILE
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise FormalReportError(
            f"cannot read {TIMELINE_FILE} in the run folder {folder.name}"
        ) from error
    try:
        timeline = Timeline.from_json(text, guard)
    except (ValueError, KeyError, TypeError) as error:
        raise FormalReportError(f"{folder.name}/{TIMELINE_FILE} is not a valid timeline") from error
    return build_run(timeline)


@dataclass(frozen=True)
class Environment:
    """Instance class and engine version read from `docs/technical.md`, None when not found."""

    instance_class: str | None
    engine: str | None
    failover_without_token: bool = False


def read_environment(technical: str, failover_workflow: str | None = None) -> Environment:
    """Parse the Database row of `docs/technical.md` and check `failover.yml` for a Cognito token.

    `failover_without_token` is True only when the workflow text was read and nothing in it
    assigns `COGNITO_ID_TOKEN`; an unreadable workflow leaves it False (no cause is stated).
    """
    row = _DATABASE_ROW.search(technical)
    text = row.group(1) if row else ""
    instance = _DB_CLASS.search(text)
    engine = _ENGINE.search(text)
    return Environment(
        instance.group(1) if instance else None,
        engine.group(1) if engine else None,
        failover_workflow is not None and not _TOKEN_ASSIGNMENT.search(failover_workflow),
    )


@dataclass(frozen=True)
class Row:
    """A metric row: value text, numeric value for the range (None when not measured)."""

    key: str
    name: str
    text: str
    number: float | None
    unit: str
    definition: str
    source: str
    resolution: str


def _direction_rows(lang: str, direction: DirectionMetrics) -> list[Row]:
    name, old, new, auth = (
        direction.name,
        direction.old_region,
        direction.new_region,
        direction.auth,
    )

    def row(
        key: str,
        text: str,
        measure: Measure | None,
        unit: str,
        parts: tuple[str, str, str],
        scale: float = 1.0,
    ) -> Row:
        number = None if measure is None or measure.value is None else measure.value * scale
        label = _text(lang, f"m_{key}", d=name)
        return Row(f"{name}:{key}", label, text, number, unit, *parts)

    def parts(
        definition: str, source: str, resolution: str, **values: object
    ) -> tuple[str, str, str]:
        return (
            _text(lang, definition, old=old, new=new, **values),
            _text(lang, source),
            _text(lang, resolution),
        )

    run_text = (
        f"{_measured(lang, auth.longest_failure_run, '', 0)} {_text(lang, 'unit_signins')}, "
        f"{_measured(lang, auth.longest_failure_seconds)}"
        if auth.longest_failure_run.value is not None
        else _measured(lang, auth.longest_failure_run)
    )
    return [
        row("write_rto", _measured(lang, direction.write_rto), direction.write_rto, "s",
            parts("d_write_rto", "s_write", "r_write")),
        row("read_rto", _measured(lang, direction.read_rto), direction.read_rto, "s",
            parts("d_read_rto", "s_read", "r_read")),
        row("unavailability", _measured(lang, direction.write_unavailability),
            direction.write_unavailability, "s", parts("d_unavailability", "s_write", "r_write")),
        row("auth", _share(lang, auth.share), auth.share, "%",
            parts("d_auth", "s_auth", "r_auth", attempts=auth.attempts, failures=auth.failures),
            100.0),
        row("auth_run", run_text, auth.longest_failure_seconds, "s",
            parts("d_auth_run", "s_auth", "r_auth")),
        row("dns", _measured(lang, direction.dns_convergence), direction.dns_convergence, "s",
            parts("d_dns", "s_dns", "r_dns")),
        row("decision", _measured(lang, direction.decision_time), direction.decision_time, "s",
            parts("d_decision", "s_github", "r_github")),
    ]  # fmt: skip


def _workflow_rows(lang: str, metrics: RunMetrics) -> list[Row]:
    rows = []
    for total in metrics.workflow_totals:
        for key, measure in (("queue", total.queue), ("run", total.run), ("total", total.total)):
            rows.append(
                Row(
                    f"{total.workflow}:{total.phase}:{key}",
                    _text(lang, f"m_{key}", w=total.workflow, p=total.phase),
                    _measured(lang, measure),
                    measure.value,
                    "s",
                    _text(lang, f"d_{key}"),
                    _text(lang, "s_github"),
                    _text(lang, "r_github"),
                )
            )
    return rows


def _lag_rows(lang: str, lag: LagStats) -> list[Row]:
    rows = []
    for key, measure in (("max", lag.max_ms), ("p95", lag.p95_ms), ("mean", lag.mean_ms)):
        stat = _text(lang, f"stat_{key}")
        rows.append(
            Row(
                f"{lag.metric}:{key}",
                _text(lang, "m_lag", metric=lag.metric, stat=stat),
                _measured(lang, measure, "ms", 1),
                measure.value,
                "ms",
                _text(lang, "d_lag", stat=stat.capitalize(), samples=lag.samples),
                _text(lang, "s_lag", metric=lag.metric),
                _text(lang, "r_lag", period=lag.period_seconds),
            )
        )
    return rows


def metric_rows(lang: str, run: RunData) -> list[Row]:
    """Every metric row of a run, in the order of the tables."""
    rows: list[Row] = []
    for direction in run.metrics.directions:
        rows += _direction_rows(lang, direction)
    rows += _workflow_rows(lang, run.metrics)
    for lag in run.metrics.lag.values():
        rows += _lag_rows(lang, lag)
    return rows


def _metrics_section(lang: str, runs: Sequence[RunData]) -> list[str]:
    lines = [_text(lang, "h_metrics"), "", _text(lang, "metrics_intro"), ""]
    all_rows = [metric_rows(lang, run) for run in runs]
    for index, (run, rows) in enumerate(zip(runs, all_rows, strict=True), start=1):
        lines += [_text(lang, "h_run_metrics", n=index, run_id=run.run_id), ""]
        table = [(r.name, r.text, r.definition, r.source, r.resolution) for r in rows]
        lines += _table(_text(lang, "metric_headers"), table)
    if len(runs) == MAX_RUNS:
        lines += _range_section(lang, all_rows)
    return lines


def _range_text(lang: str, left: Row, right: Row | None) -> str:
    if right is None or left.number is None or right.number is None:
        return _text(lang, "range_missing")
    low, high = sorted((left.number, right.number))
    digits = 1 if left.unit == "ms" or left.unit == "%" else 2
    return _text(
        lang,
        "range_value",
        low=f"{low:.{digits}f} {left.unit}",
        high=f"{high:.{digits}f} {left.unit}",
    )


def _range_section(lang: str, all_rows: Sequence[Sequence[Row]]) -> list[str]:
    second = {row.key: row for row in all_rows[1]}
    table = [
        (row.name, row.text, other.text if other else _text(lang, "dash"),
         _range_text(lang, row, other))
        for row in all_rows[0]
        for other in (second.get(row.key),)
    ]  # fmt: skip
    return [
        _text(lang, "h_range"),
        "",
        _text(lang, "range_intro"),
        "",
        *_table(_text(lang, "range_headers"), table),
    ]


def _rpo_headline(lang: str, ledger: LedgerReport | None) -> str:
    if ledger is None:
        return _text(lang, "headline_rpo_none")
    low, high = ledger.rpo_lost_min, ledger.rpo_lost_max
    if ledger.rpo_status == RPO_ZERO_LOSS:
        return _text(lang, "headline_rpo_zero")
    if ledger.rpo_status == RPO_LOSS:
        return _text(lang, "headline_rpo_loss", low=low, high=high)
    if ledger.rpo_status == RPO_NOT_VERIFIABLE:
        return _text(lang, "headline_rpo_unverifiable", low=low, high=high)
    return _text(lang, "headline_rpo_none")


def _headline_section(lang: str, runs: Sequence[RunData]) -> list[str]:
    table = []
    for index, run in enumerate(runs, start=1):
        rtos = [_measured(lang, direction.write_rto) for direction in run.metrics.directions]
        table.append((index, run.date, run.verdict, *rtos, _rpo_headline(lang, run.ledger)))
    return [_text(lang, "h_headline"), "", *_table(_text(lang, "headline_headers"), table)]


def _phase_rows(run: RunData) -> list[tuple[str, str, str, str]]:
    rows = []
    for window in run.metrics.phases.values():
        duration = (
            "-" if window.end is None else f"{(window.end - window.start).total_seconds():.1f} s"
        )
        rows.append((window.name, _stamp(window.start), _stamp(window.end), duration))
    return rows


def _parse(value: object) -> datetime | None:
    return datetime.fromisoformat(value) if isinstance(value, str) else None


def _step_starts(timeline: Timeline) -> dict[tuple[str, str], datetime]:
    starts: dict[tuple[str, str], datetime] = {}
    for event in timeline.events("workflow_step"):
        begin = _parse(event.data.get("start"))
        if event.data.get("event") == "step" and begin is not None:
            starts.setdefault((str(event.data.get("phase")), str(event.data.get("step"))), begin)
    return starts


def _workflow_events(lang: str, timeline: Timeline, phase: str) -> list[tuple[datetime, str]]:
    events: list[tuple[datetime, str]] = []
    for event in timeline.events("workflow_step"):
        data = event.data
        if data.get("phase") != phase:
            continue
        values = {"workflow": str(data.get("workflow")), "phase": phase}
        started, updated = _parse(data.get("started")), _parse(data.get("updated"))
        if data.get("event") == "dispatch":
            events.append((event.time_utc, _text(lang, "ev_dispatch", **values)))
        if data.get("event") == "run" and started is not None:
            events.append((started, _text(lang, "ev_run_started", **values)))
        if data.get("event") == "run" and updated is not None:
            events.append((updated, _text(lang, "ev_run_ended", **values)))
    return events


def _step_events(
    lang: str, run: RunData, direction: DirectionMetrics
) -> list[tuple[datetime, str]]:
    starts = _step_starts(run.timeline)
    events = []
    for step in direction.breakdown.steps:
        begin = starts.get((step.phase, step.name))
        if step.category in TIMELINE_CATEGORIES and step.seconds >= 1.0 and begin is not None:
            label = _text(
                lang,
                "ev_step",
                name=step.name,
                category=_text(lang, f"cat_{step.category}"),
                seconds=f"{step.seconds:.0f}",
            )
            events.append((begin, label))
    return events


def _dns_event(lang: str, run: RunData, phases: Sequence[str]) -> list[tuple[datetime, str]]:
    traffic = [
        _parse(event.data.get("start"))
        for event in run.timeline.events("workflow_step")
        if event.data.get("event") == "step"
        and event.data.get("step") == TRAFFIC_STEP
        and event.data.get("phase") in phases
    ]
    begin = next((item for item in traffic if item is not None), None)
    if begin is None:
        return []
    changes = [
        event
        for event in run.timeline.events("dns")
        if not event.data.get("first") and event.time_utc >= begin
    ]
    return [(changes[0].time_utc, _text(lang, "ev_dns"))] if changes else []


def _write_events(
    lang: str, run: RunData, outage: PhaseWindow, end: datetime | None, new_region: str
) -> list[tuple[datetime, str]]:
    writes = [
        item
        for item in run.timeline.observations()
        if item.probe == PROBE_WRITE
        and item.start_utc >= outage.start
        and (end is None or item.start_utc < end)
    ]
    failed = next(
        (item for item in writes if not item.ok and not is_permanent_error(item.status, 0)), None
    )
    if failed is None:
        return []
    events = [(failed.start_utc, _text(lang, "ev_first_failed"))]
    recovered = next(
        (
            item
            for item in writes
            if item.ok
            and item.served_by_region == new_region
            and item.start_utc >= failed.start_utc
        ),
        None,
    )
    if recovered is not None:
        events.append((recovered.end_utc, _text(lang, "ev_first_new", region=new_region)))
    return events


def _direction_events(
    lang: str, run: RunData, direction: DirectionMetrics
) -> list[tuple[datetime, str]]:
    spec = next(item for item in DIRECTIONS if item.name == direction.name)
    windows = run.metrics.phases
    outage, steady = windows.get(spec.outage_phase), windows.get(spec.steady_phase)
    if outage is None:
        return []
    window_end = None if steady is None else steady.end
    events = [(outage.start, _text(lang, "ev_start", phase=spec.outage_phase))]
    for phase in spec.workflow_phases:
        events += _workflow_events(lang, run.timeline, phase)
    events += _step_events(lang, run, direction)
    events += _dns_event(lang, run, spec.workflow_phases)
    events += _write_events(lang, run, outage, window_end, direction.new_region)
    if steady is not None:
        events.append((steady.start, _text(lang, "ev_steady", phase=spec.steady_phase)))
    return sorted(events, key=lambda item: item[0])


def _timeline_section(lang: str, runs: Sequence[RunData]) -> list[str]:
    lines = [_text(lang, "h_timeline"), "", _text(lang, "timeline_intro"), ""]
    for index, run in enumerate(runs, start=1):
        lines += [_text(lang, "h_phases", n=index), ""]
        phases = _phase_rows(run)
        if phases:
            lines += _table(_text(lang, "phase_headers"), phases)
        else:
            lines += [_text(lang, "no_phases"), ""]
        for direction in run.metrics.directions:
            label = DIRECTION_LABELS[lang][direction.name]
            lines += [_text(lang, "h_direction", n=index, direction=label), ""]
            events = _direction_events(lang, run, direction)
            if not events:
                lines += [_text(lang, "no_events"), ""]
                continue
            origin = events[0][0]
            rows = [
                (f"+{(moment - origin).total_seconds():.1f} s", format_utc(moment), text)
                for moment, text in events
            ]
            lines += _table(_text(lang, "timeline_headers"), rows)
    return lines


def _breakdown_section(lang: str, runs: Sequence[RunData]) -> list[str]:
    lines: list[str] = []
    for index, run in enumerate(runs, start=1):
        lines += [_text(lang, "h_breakdown", n=index), ""]
        rows = [
            (direction.name, _text(lang, f"cat_{name}"), _measured(lang, measure))
            for direction in run.metrics.directions
            for name, measure in direction.breakdown.categories.items()
            if measure.value is not None
        ]
        lines += _table(_text(lang, "breakdown_headers"), rows)
    return lines


def _yes_no(lang: str, value: bool | None) -> str:
    if value is None:
        return _text(lang, "ledger_none")
    return _text(lang, "yes" if value else "no")


def _ledger_row(lang: str, index: int, ledger: LedgerReport | None) -> tuple[object, ...]:
    none = _text(lang, "ledger_none")
    if ledger is None:
        return (index, *([none] * 7))
    consistency = ledger.consistency
    duplicates = None if consistency is None else consistency.duplicate_keys
    return (
        index,
        ledger.baseline_count,
        ledger.acked_expected,
        none if ledger.stored_count is None else ledger.stored_count,
        ledger.band,
        _yes_no(lang, ledger.balance_ok),
        none if consistency is None else _yes_no(lang, consistency.consistent),
        none if duplicates is None else duplicates,
    )


def _ledger_section(lang: str, runs: Sequence[RunData]) -> list[str]:
    rows = [_ledger_row(lang, index, run.ledger) for index, run in enumerate(runs, start=1)]
    return [_text(lang, "h_ledger"), "", *_table(_text(lang, "ledger_headers"), rows)]


def _rto_finding(lang: str, direction: DirectionMetrics) -> list[str]:
    name = direction.name
    if direction.write_rto.value is None:
        reason = _reason(lang, direction.write_rto.reason)
        return [_text(lang, "f_rto_missing", d=name, reason=reason)]
    write = _measured(lang, direction.write_rto)
    if direction.write_unavailability.value is None:
        reason = _reason(lang, direction.write_unavailability.reason)
        lines = [_text(lang, "f_rto_no_unavailability", d=name, write=write, reason=reason)]
    else:
        unavail = _measured(lang, direction.write_unavailability)
        lines = [_text(lang, "f_rto", d=name, unavail=unavail, write=write)]
    if direction.read_rto.value is None:
        reason = _reason(lang, direction.read_rto.reason)
        return [*lines, _text(lang, "f_rto_read_missing", d=name, reason=reason)]
    return [*lines, _text(lang, "f_rto_read", d=name, read=_measured(lang, direction.read_rto))]


def _breakdown_finding(lang: str, direction: DirectionMetrics) -> list[str]:
    measured = {
        name: value
        for name in BREAKDOWN_CATEGORIES
        if (value := direction.breakdown.categories[name].value) is not None
    }
    if not measured:
        return []
    largest = max(measured, key=lambda name: measured[name])
    return [
        _text(
            lang,
            "f_breakdown",
            d=direction.name,
            category=_text(lang, f"cat_{largest}"),
            seconds=f"{measured[largest]:.0f}",
            total=f"{sum(measured.values()):.0f}",
        )
    ]


def _dns_finding(lang: str, direction: DirectionMetrics) -> str:
    measure = direction.dns_convergence
    if measure.value is None:
        return _text(lang, "f_dns_missing", d=direction.name, reason=_reason(lang, measure.reason))
    key = "f_dns_negative" if measure.value < 0 else "f_dns_positive"
    return _text(lang, key, d=direction.name, value=_measured(lang, measure))


def _auth_finding(lang: str, direction: DirectionMetrics) -> list[str]:
    auth = direction.auth
    if auth.share.value is None:
        reason = _reason(lang, auth.share.reason)
        return [_text(lang, "f_auth_missing", d=direction.name, reason=reason)]
    lines = [_auth_statement(lang, direction)]
    for step in direction.breakdown.steps:
        if step.category == CATEGORY_COGNITO and step.seconds >= 1.0:
            lines.append(
                _text(lang, "f_auth_replica", step=step.name, seconds=f"{step.seconds:.0f}")
            )
    return lines


def _auth_statement(lang: str, direction: DirectionMetrics) -> str:
    auth = direction.auth
    return _text(
        lang,
        "f_auth",
        d=direction.name,
        share=_share(lang, auth.share),
        failures=auth.failures,
        attempts=auth.attempts,
        run=_measured(lang, auth.longest_failure_run, "", 0),
        seconds=_measured(lang, auth.longest_failure_seconds),
    )


def _deposit_findings(lang: str, run: RunData, cause_known: bool = False) -> list[str]:
    if not run.deposits:
        return [_text(lang, "f_deposits_none")]
    labels = OUTCOME_LABELS[lang]
    outcomes = "; ".join(
        f"{phase}: {labels.get(outcome, outcome)}" for phase, outcome in run.deposits
    )
    skipped = [outcome for _, outcome in run.deposits if outcome == "skipped"]
    lines = [_text(lang, "f_deposits", outcomes=outcomes)]
    if len(skipped) == len(run.deposits) == len(DIRECTIONS):
        lines.append(_text(lang, "f_deposits_skipped"))
        if cause_known:
            lines.append(_text(lang, "f_deposits_cause"))
    elif skipped:
        lines.append(_text(lang, "f_deposits_skipped_some"))
    return lines


def _rpo_finding(lang: str, ledger: LedgerReport | None) -> str:
    if ledger is None:
        return _text(lang, "f_rpo_missing")
    values = {
        "stored": "?" if ledger.stored_count is None else ledger.stored_count,
        "expected": ledger.acked_expected,
        "band": ledger.band,
        "low": ledger.rpo_lost_min,
        "high": ledger.rpo_lost_max,
    }
    if ledger.rpo_status == RPO_ZERO_LOSS:
        return _text(lang, "f_rpo_zero", **values)
    if ledger.rpo_status == RPO_LOSS:
        return _text(lang, "f_rpo_loss", **values)
    if ledger.rpo_status == RPO_NOT_VERIFIABLE:
        return _text(lang, "f_rpo_unverifiable", **values)
    return _text(lang, "f_rpo_none")


def _lag_findings(lang: str, metrics: RunMetrics) -> list[str]:
    lines = []
    for lag in metrics.lag.values():
        if lag.max_ms.value is None:
            reason = _reason(lang, lag.max_ms.reason)
            lines.append(_text(lang, "f_lag_missing", metric=lag.metric, reason=reason))
            continue
        lines.append(
            _text(
                lang,
                "f_lag",
                metric=lag.metric,
                max=_measured(lang, lag.max_ms, "ms", 1),
                p95=_measured(lang, lag.p95_ms, "ms", 1),
                mean=_measured(lang, lag.mean_ms, "ms", 1),
                samples=lag.samples,
                period=lag.period_seconds,
            )
        )
    return lines


def run_findings(lang: str, run: RunData, deposit_cause_known: bool = False) -> list[str]:
    """The findings of one run, chosen by rule from its data."""
    reason = _text(lang, "f_reason", reason=run.reason) if run.reason else ""
    findings = [_text(lang, "f_verdict", verdict=run.verdict, reason=reason)]
    for direction in run.metrics.directions:
        findings += _rto_finding(lang, direction)
        findings += _breakdown_finding(lang, direction)
        findings.append(_dns_finding(lang, direction))
        findings += _auth_finding(lang, direction)
    changes = sum(1 for event in run.timeline.events("dns") if not event.data.get("first"))
    if changes > len(run.metrics.directions):
        findings.append(
            _text(lang, "f_dns_changes", changes=changes, switches=len(run.metrics.directions))
        )
    findings += _deposit_findings(lang, run, deposit_cause_known)
    findings.append(_rpo_finding(lang, run.ledger))
    findings += _lag_findings(lang, run.metrics)
    if run.ledger is not None:
        findings += [_text(lang, "f_ledger_problem", text=item) for item in run.ledger.problems]
    if run.refused:
        findings.append(_text(lang, "f_refused", count=run.refused))
    return findings


def _findings_section(lang: str, runs: Sequence[RunData], cause_known: bool) -> list[str]:
    lines = [_text(lang, "h_findings"), "", _text(lang, "findings_intro"), ""]
    for index, run in enumerate(runs, start=1):
        lines += [_text(lang, "h_run_findings", n=index, run_id=run.run_id), ""]
        lines += [f"- {item}" for item in run_findings(lang, run, cause_known)]
        lines.append("")
    return lines


def _limitations_section(lang: str, runs: Sequence[RunData]) -> list[str]:
    period = max(
        (lag.period_seconds for run in runs for lag in run.metrics.lag.values()), default=60
    )
    keys = (
        "lim_runs_one" if len(runs) == 1 else "lim_runs_two",
        "lim_dns",
        "lim_planned",
        "lim_manual",
        "lim_load",
        "lim_resolution",
        "lim_settle",
        "lim_clock",
        "lim_band",
    )
    items = [_text(lang, key, period=period) for key in keys]
    return [_text(lang, "h_limitations"), "", *[f"- {item}" for item in items], ""]


def _environment_section(lang: str, runs: Sequence[RunData], environment: Environment) -> list[str]:
    first = runs[0]
    lines = [
        _text(lang, "h_environment"),
        "",
        _text(lang, "env_regions", primary=first.primary, secondary=first.secondary),
    ]
    if environment.instance_class and environment.engine:
        lines.append(
            _text(
                lang,
                "env_database",
                instance_class=environment.instance_class,
                engine=environment.engine,
            )
        )
    else:
        lines.append(_text(lang, "env_database_missing"))
    return [*lines, _text(lang, "env_other"), _text(lang, "env_account"), ""]


def render_formal_report(lang: str, runs: Sequence[RunData], environment: Environment) -> str:
    """The formal report in one language ("en" or "es"); pure and deterministic."""
    if not runs or len(runs) > MAX_RUNS:
        raise FormalReportError(f"the formal report needs one or {MAX_RUNS} runs")
    if len({(run.primary, run.secondary) for run in runs}) != 1:
        raise FormalReportError("the runs used different regions and cannot share one report")
    dates = ", ".join(dict.fromkeys(run.date for run in runs))
    names = ", ".join(f"`{run.run_id}`" for run in runs)
    lines = [
        _text(lang, "title"),
        "",
        _text(lang, "other_copy"),
        "",
        _text(lang, "run_date", dates=dates),
        "",
        _text(lang, "generated", count=len(runs), runs=names),
        "",
        _text(lang, "h_purpose"),
        "",
        _text(lang, "purpose"),
        "",
        _text(lang, "h_method"),
        "",
        _text(lang, "method"),
        "",
        *_environment_section(lang, runs, environment),
        *_headline_section(lang, runs),
        *_metrics_section(lang, runs),
        *_timeline_section(lang, runs),
        *_breakdown_section(lang, runs),
        *_ledger_section(lang, runs),
        *_findings_section(lang, runs, environment.failover_without_token),
        *_limitations_section(lang, runs),
        _text(lang, "h_sources"),
        "",
        _text(lang, "sources", runs=names, dates=dates),
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


@dataclass(frozen=True)
class FormalDocuments:
    """The two generated documents, as text."""

    english: str
    spanish: str


def build_documents(
    runs: Sequence[RunData], technical: str, failover_workflow: str | None = None
) -> FormalDocuments:
    """Both documents from the runs, `docs/technical.md` and (optional) `failover.yml`."""
    environment = read_environment(technical, failover_workflow)
    return FormalDocuments(
        render_formal_report(EN, runs, environment), render_formal_report(ES, runs, environment)
    )


def write_documents(
    documents: FormalDocuments, repo_root: Path, guard: OutputGuard
) -> tuple[Path, Path]:
    """Write both files, or neither when the guard refuses one (all or nothing)."""
    english = (repo_root / EN_DOCUMENT, documents.english)
    spanish = (repo_root / ES_DOCUMENT, documents.spanish)
    for path, text in (english, spanish):
        reason = guard.reason(text)
        if reason is not None:
            raise FormalReportError(f"{path.name} was not written because {reason}")
    for path, text in (english, spanish):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
    return english[0], spanish[0]


def generate(folders: Sequence[Path], repo_root: Path, guard: OutputGuard) -> tuple[Path, Path]:
    """Read the run folders and write `docs/dr-test-report.md` and `docs-es/dr-test-report.md`."""
    if len(folders) > MAX_RUNS or len({folder.resolve() for folder in folders}) != len(folders):
        raise FormalReportError(f"give one or {MAX_RUNS} different run folders")
    try:
        technical = (repo_root / TECHNICAL_DOCUMENT).read_text(encoding="utf-8")
    except OSError as error:
        raise FormalReportError(f"cannot read {TECHNICAL_DOCUMENT.as_posix()}") from error
    try:
        failover = (repo_root / FAILOVER_WORKFLOW).read_text(encoding="utf-8")
    except OSError:
        failover = None
    runs = [load_run(folder, guard) for folder in folders]
    return write_documents(build_documents(runs, technical, failover), repo_root, guard)


def _command_guard(runner_dir: Path, environ: Mapping[str, str], err: TextIO) -> OutputGuard:
    """Guard with the settings secrets when they load; else shape checks only, with a warning."""
    try:
        return OutputGuard(load_settings(runner_dir, environ).secret_values())
    except (SettingsError, OSError):
        err.write(
            "formal-report: the settings could not be loaded, so registered secret values are "
            "not checked; only the shape checks of the output guard apply.\n"
        )
        return OutputGuard()


def formal_report_command(
    folders: Sequence[Path],
    repo_root: Path = REPO_ROOT,
    out: TextIO | None = None,
    err: TextIO | None = None,
    runner_dir: Path = RUNNER_DIR,
    environ: Mapping[str, str] | None = None,
) -> int:
    """The `formal-report` subcommand: exit 0 when both files were written, 2 otherwise."""
    out, err = out or sys.stdout, err or sys.stderr
    try:
        guard = _command_guard(runner_dir, os.environ if environ is None else environ, err)
        english, spanish = generate(folders, repo_root, guard)
    except FormalReportError as error:
        err.write(f"formal-report: {error}\n")
        return 2
    for path in (english, spanish):
        out.write(f"written: {path.relative_to(repo_root).as_posix()}\n")
    return 0
